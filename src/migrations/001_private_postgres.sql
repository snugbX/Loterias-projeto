CREATE SCHEMA IF NOT EXISTS lottery_private;
REVOKE ALL ON SCHEMA lottery_private FROM PUBLIC;

CREATE TABLE IF NOT EXISTS lottery_private.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    plan TEXT NOT NULL DEFAULT 'free' CHECK (plan IN ('free', 'premium')),
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    last_login_at TEXT,
    terms_accepted_at TEXT,
    terms_version TEXT
);
CREATE TABLE IF NOT EXISTS lottery_private.usage_days (
    user_id BIGINT NOT NULL REFERENCES lottery_private.users(id) ON DELETE CASCADE,
    usage_date TEXT NOT NULL,
    generated_games INTEGER NOT NULL DEFAULT 0 CHECK (generated_games >= 0),
    PRIMARY KEY (user_id, usage_date)
);
CREATE TABLE IF NOT EXISTS lottery_private.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES lottery_private.users(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    target_user_id BIGINT REFERENCES lottery_private.users(id) ON DELETE SET NULL,
    details_json TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS lottery_private.generated_games (
    owner_key TEXT NOT NULL,
    filename TEXT NOT NULL,
    lottery_type TEXT NOT NULL,
    created_at TEXT NOT NULL,
    games_json TEXT NOT NULL,
    PRIMARY KEY (owner_key, filename)
);
CREATE INDEX IF NOT EXISTS idx_users_email ON lottery_private.users(email);
CREATE INDEX IF NOT EXISTS idx_audit_created ON lottery_private.audit_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_generated_games_owner_lottery
    ON lottery_private.generated_games(owner_key, lottery_type, filename);
REVOKE ALL ON ALL TABLES IN SCHEMA lottery_private FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA lottery_private FROM PUBLIC;
